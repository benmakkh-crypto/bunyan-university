$UWCIV_PAGES_DEFAULT = $UWCIV_PAGES;
function uwciv_pages_override_file() { return dirname(__DIR__) . '/_private/pages.json'; }
function uwciv_pages_overrides()
{
    $f = uwciv_pages_override_file();
    $d = is_file($f) ? json_decode((string) file_get_contents($f), true) : [];
    return is_array($d) ? $d : [];
}
foreach (uwciv_pages_overrides() as $__k => $__pg) if (is_array($__pg) && isset($__pg['lead'], $__pg['sections'])) $UWCIV_PAGES[$__k] = $__pg;
unset($__k, $__pg);
