/* البيانات النهائية: الافتراضي + تعديلات المشرف */
function uwciv_regs_path() { return dirname(__DIR__) . '/_private/regs.json'; }
function uwciv_regs()
{
    $s = ['docs' => uwciv_regs_seed_docs(), 'powers' => uwciv_regs_seed_powers()];
    $f = uwciv_regs_path();
    if (is_file($f)) {
        $j = json_decode((string) @file_get_contents($f), true);
        if (is_array($j)) {
            if (isset($j['docs']) && is_array($j['docs'])) {
                // دمج: الوثائق المحفوظة أولًا، مع إضافة أدلة الكليات الجديدة إن وُجدت
                $ids = array_column($j['docs'], 'id');
                foreach ($s['docs'] as $d) if (!in_array($d['id'], $ids, true) && $d['cat'] === 'guides') $j['docs'][] = $d;
                $s['docs'] = $j['docs'];
            }
            if (isset($j['powers']) && is_array($j['powers'])) $s['powers'] = $j['powers'];
        }
    }
    return $s;
}
function uwciv_regs_save(array $s)
{
    $f = uwciv_regs_path();
    if (!is_dir(dirname($f))) @mkdir(dirname($f), 0755, true);
    return @file_put_contents($f, json_encode($s, JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT), LOCK_EX) !== false;
}
