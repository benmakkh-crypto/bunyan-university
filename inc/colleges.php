function uwciv_college_url($slug) { return '/college/' . $slug; }
function uwciv_college_counts()
{
    $d = 0; foreach ($GLOBALS['UWCIV_COLLEGES'] as $c) $d += count($c['deps']);
    return [count($GLOBALS['UWCIV_COLLEGES']), $d];
}

/* ===== تعديلات الكليات من لوحة التحكم (/admin/college.php) — تُدمج فوق البيانات أعلاه ===== */
$UWCIV_COLLEGES_DEFAULT = $UWCIV_COLLEGES;
function uwciv_colleges_override_file() { return dirname(__DIR__) . '/_private/colleges.json'; }
function uwciv_colleges_overrides()
{
    $f = uwciv_colleges_override_file();
    $d = is_file($f) ? json_decode((string) file_get_contents($f), true) : [];
    return is_array($d) ? $d : [];
}
foreach (uwciv_colleges_overrides() as $__slug => $__ov) {
    if (!isset($UWCIV_COLLEGES[$__slug]) || !is_array($__ov)) continue;
    foreach (['n', 'tag', 'about', 'vision', 'mission', 'goals', 'deps', 'st', 'jobs', 'i', 'c', 'dean', 'dean_msg', 'email', 'phone', 'admission', 'hours', 'fees_note'] as $__k)
        if (array_key_exists($__k, $__ov)) $UWCIV_COLLEGES[$__slug][$__k] = $__ov[$__k];
}
unset($__slug, $__ov, $__k);
